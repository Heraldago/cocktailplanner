export function lookupIngredientTranslation(name: string, lang: Language): string {
  if (lang === 'it') return name;

  const lower = name.toLowerCase().trim();

  // Exact & substring match priority
  for (const [key, map] of Object.entries(INGREDIENT_TRANSLATION_MAP)) {
    if (lower === key || lower.includes(key)) {
      return map[lang] || map.en;
    }
  }

  return name;
}
